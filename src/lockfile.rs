//! Reading and writing `Cargo.lock` in formats 3 and 4, byte for byte as
//! cargo writes them (`core/resolver/encode.rs` and `ops/lockfile.rs`).

use std::{
    collections::{BTreeMap, HashMap},
    fmt::{self, Write as _},
};

use semver::Version;
use serde::Deserialize;

use crate::{error::LockfileError, names::PackageName, summary::RustVersion};

/// The `source` cargo records for packages from crates.io, whichever
/// protocol fetched them.
const CRATES_IO_SOURCE: &str = "registry+https://github.com/rust-lang/crates.io-index";

const MARKER_LINE: &str = "# This file is automatically @generated by Cargo.";
const EXTRA_LINE: &str = "# It is not intended for manual editing.";

/// The format version of a lock file.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum LockfileVersion {
    /// Format 3, which cargo writes for workspaces whose lowest
    /// `rust-version` is below 1.83.
    V3,
    /// Format 4, cargo's default.
    V4,
}

impl LockfileVersion {
    /// The format cargo writes for a new lock file of a workspace whose
    /// lowest member `rust-version` is `rust_version` (cargo's
    /// `ResolveVersion::with_rust_version`). Workspaces with members below
    /// Rust 1.53 would get formats this crate does not write, so they get 3.
    pub(crate) fn for_rust_version(rust_version: Option<&RustVersion>) -> LockfileVersion {
        let v4_minimum = RustVersion::from(&Version::new(1, 83, 0));
        match rust_version {
            Some(rust_version) if *rust_version < v4_minimum => LockfileVersion::V3,
            Some(_) | None => LockfileVersion::V4,
        }
    }

    fn number(self) -> u32 {
        match self {
            LockfileVersion::V3 => 3,
            LockfileVersion::V4 => 4,
        }
    }
}

/// Where a locked package comes from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum PackageSource {
    /// A path package: a workspace member or path dependency. Lock files
    /// record no source for these.
    Path,
    /// crates.io.
    Registry,
}

/// A package a lock file records. Ordered as cargo orders lock file
/// entries: by name, then version, then source with paths first.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct PackageId {
    /// The crate name.
    pub name: PackageName,
    /// The version.
    pub version: Version,
    /// Where it comes from.
    pub source: PackageSource,
}

/// One `[[package]]` of a lock file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockedPackage {
    /// Which package.
    pub id: PackageId,
    /// The sha256 of the `.crate` file, for registry packages.
    pub checksum: Option<String>,
    /// The packages it depends on, of all kinds, sorted.
    pub dependencies: Vec<PackageId>,
}

/// A `Cargo.lock`: what [`Lockfile::parse`] reads and what
/// [`resolve`](crate::resolve) produces. Its [`Display`](fmt::Display)
/// writes it byte for byte as cargo does.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Lockfile {
    version: LockfileVersion,
    /// The comment lines at the top of the file besides the two cargo
    /// writes, which cargo keeps when it rewrites the file.
    header: Vec<String>,
    /// Sorted by id.
    packages: Vec<LockedPackage>,
    /// The `[metadata]` table, which cargo keeps when it rewrites the file.
    metadata: BTreeMap<String, String>,
}

impl Lockfile {
    /// Parses a `Cargo.lock` of format 3 or 4. Dependency entries that
    /// match no single package of the file are dropped, as cargo drops
    /// them.
    ///
    /// # Errors
    ///
    /// [`LockfileError`] when the text is not such a lock file, or records a
    /// source other than crates.io and paths.
    pub fn parse(text: &str) -> Result<Lockfile, LockfileError> {
        let toml: TomlLockfile =
            toml::from_str(text).map_err(|source| LockfileError::Parse(Box::new(source)))?;
        let version = match toml.version {
            Some(3) => LockfileVersion::V3,
            Some(4) => LockfileVersion::V4,
            other => return Err(LockfileError::UnsupportedVersion { version: other }),
        };

        let mut ids = Vec::new();
        for package in toml.package.iter().flatten() {
            let name = PackageName::new(package.name.as_str());
            let source = match package.source.as_deref() {
                None => PackageSource::Path,
                Some(CRATES_IO_SOURCE) => PackageSource::Registry,
                Some(other) => {
                    return Err(LockfileError::UnsupportedSource {
                        name,
                        source_id: other.to_owned(),
                    });
                }
            };
            let parsed = Version::parse(&package.version).map_err(|source| {
                LockfileError::InvalidVersion {
                    name: name.clone(),
                    text: package.version.clone(),
                    source,
                }
            })?;
            let id = PackageId {
                name,
                version: parsed,
                source,
            };
            if ids.contains(&id) {
                return Err(LockfileError::DuplicatePackage {
                    name: id.name,
                    version: id.version,
                });
            }
            ids.push(id);
        }

        let mut by_name: HashMap<&str, Vec<&PackageId>> = HashMap::new();
        for id in &ids {
            by_name.entry(id.name.as_str()).or_default().push(id);
        }

        let mut packages = Vec::new();
        for (package, id) in toml.package.iter().flatten().zip(&ids) {
            let mut dependencies = Vec::new();
            for text in package.dependencies.iter().flatten() {
                let reference =
                    parse_reference(text).ok_or_else(|| LockfileError::InvalidDependency {
                        name: id.name.clone(),
                        text: text.clone(),
                    })?;
                let candidates = by_name
                    .get(reference.name)
                    .map(Vec::as_slice)
                    .unwrap_or(&[]);
                let matching: Vec<&PackageId> = candidates
                    .iter()
                    .copied()
                    .filter(|candidate| {
                        reference
                            .version
                            .is_none_or(|version| candidate.version.to_string() == version)
                            && reference.source.is_none_or(|source| {
                                source == CRATES_IO_SOURCE
                                    && candidate.source == PackageSource::Registry
                            })
                    })
                    .collect();
                // Without a source, a path package wins over registry ones of
                // the same name and version, as in cargo's `into_resolve`.
                let target = match matching.as_slice() {
                    [only] => Some(*only),
                    several => {
                        let mut paths = several
                            .iter()
                            .filter(|candidate| candidate.source == PackageSource::Path);
                        match (reference.source, paths.next(), paths.next()) {
                            (None, Some(path), None) => Some(*path),
                            _ => None,
                        }
                    }
                };
                match target {
                    Some(target) => dependencies.push(target.clone()),
                    None => tracing::debug!(
                        package = %id.name,
                        dependency = %text,
                        "dropping a lock file dependency that matches no single package"
                    ),
                }
            }
            packages.push(LockedPackage {
                id: id.clone(),
                checksum: package.checksum.clone(),
                dependencies,
            });
        }

        Ok(Lockfile::new(
            version,
            extra_header(text),
            toml.metadata.unwrap_or_default(),
            packages,
        ))
    }

    /// A lock file of `packages`, sorted as cargo sorts them.
    pub(crate) fn new(
        version: LockfileVersion,
        header: Vec<String>,
        metadata: BTreeMap<String, String>,
        mut packages: Vec<LockedPackage>,
    ) -> Lockfile {
        packages.sort_by(|a, b| a.id.cmp(&b.id));
        for package in &mut packages {
            package.dependencies.sort();
            package.dependencies.dedup();
        }
        Lockfile {
            version,
            header,
            packages,
            metadata,
        }
    }

    /// The format version.
    pub fn version(&self) -> LockfileVersion {
        self.version
    }

    /// The packages, sorted by id.
    pub fn packages(&self) -> &[LockedPackage] {
        &self.packages
    }

    pub(crate) fn header(&self) -> &[String] {
        &self.header
    }

    pub(crate) fn metadata(&self) -> &BTreeMap<String, String> {
        &self.metadata
    }
}

impl fmt::Display for Lockfile {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&write_lockfile(self))
    }
}

#[derive(Deserialize)]
struct TomlLockfile {
    version: Option<u32>,
    package: Option<Vec<TomlPackage>>,
    metadata: Option<BTreeMap<String, String>>,
}

#[derive(Deserialize)]
struct TomlPackage {
    name: String,
    version: String,
    source: Option<String>,
    checksum: Option<String>,
    dependencies: Option<Vec<String>>,
}

struct Reference<'a> {
    name: &'a str,
    version: Option<&'a str>,
    source: Option<&'a str>,
}

/// `name`, `name version` or `name version (source)`.
fn parse_reference(text: &str) -> Option<Reference<'_>> {
    let mut parts = text.splitn(3, ' ');
    let name = parts.next()?;
    let version = parts.next();
    let source = match parts.next() {
        Some(source) => Some(source.strip_prefix('(')?.strip_suffix(')')?),
        None => None,
    };
    Some(Reference {
        name,
        version,
        source,
    })
}

/// The leading comment lines cargo keeps: all but its own two lines.
fn extra_header(text: &str) -> Vec<String> {
    let mut comments = text.lines().take_while(|line| line.starts_with('#'));
    let mut header = Vec::new();
    if let Some(first) = comments.next() {
        if first != MARKER_LINE {
            header.push(first.to_owned());
        }
        if let Some(second) = comments.next() {
            if second != EXTRA_LINE {
                header.push(second.to_owned());
            }
            header.extend(comments.map(str::to_owned));
        }
    }
    header
}

/// A dependency entry as cargo encodes it: the version only if the lock
/// has several versions of the name, the source only if it has several
/// packages of the name and version. Sorted as strings, as cargo sorts
/// its `TomlLockfilePackageId`s.
#[derive(PartialEq, Eq, PartialOrd, Ord)]
struct EncodedReference {
    name: String,
    version: Option<String>,
    source: Option<&'static str>,
}

/// Writes a lock file as cargo's `serialize_resolve` does.
fn write_lockfile(lockfile: &Lockfile) -> String {
    let mut counts: HashMap<&PackageName, HashMap<&Version, usize>> = HashMap::new();
    for package in &lockfile.packages {
        *counts
            .entry(&package.id.name)
            .or_default()
            .entry(&package.id.version)
            .or_default() += 1;
    }
    let encode = |id: &PackageId| {
        let versions = counts.get(&id.name);
        let same_version = versions
            .and_then(|versions| versions.get(&id.version))
            .copied()
            .unwrap_or_default();
        let unique_version = same_version == 1;
        let unique_name = unique_version && versions.is_some_and(|versions| versions.len() == 1);
        EncodedReference {
            name: id.name.to_string(),
            version: (!unique_name).then(|| id.version.to_string()),
            source: if unique_version {
                None
            } else {
                source_string(id.source)
            },
        }
    };

    let mut out = String::new();
    out.push_str(MARKER_LINE);
    out.push('\n');
    out.push_str(EXTRA_LINE);
    out.push('\n');
    for line in &lockfile.header {
        out.push_str(line);
        out.push('\n');
    }
    let _ = write!(out, "version = {}\n\n", lockfile.version.number());

    for package in &lockfile.packages {
        out.push_str("[[package]]\n");
        let _ = writeln!(out, "name = {}", quote(package.id.name.as_str()));
        let _ = writeln!(out, "version = {}", quote(&package.id.version.to_string()));
        if let Some(source) = source_string(package.id.source) {
            let _ = writeln!(out, "source = {}", quote(source));
        }
        if let Some(checksum) = &package.checksum {
            let _ = writeln!(out, "checksum = {}", quote(checksum));
        }
        let mut dependencies: Vec<EncodedReference> =
            package.dependencies.iter().map(&encode).collect();
        dependencies.sort();
        dependencies.dedup();
        if !dependencies.is_empty() {
            out.push_str("dependencies = [\n");
            for dependency in &dependencies {
                let mut text = dependency.name.clone();
                if let Some(version) = &dependency.version {
                    text.push(' ');
                    text.push_str(version);
                }
                if let Some(source) = dependency.source {
                    let _ = write!(text, " ({source})");
                }
                let _ = writeln!(out, " {},", quote(&text));
            }
            out.push_str("]\n");
        }
        out.push('\n');
    }

    if !lockfile.metadata.is_empty() {
        out.push_str("[metadata]\n");
        for (key, value) in &lockfile.metadata {
            let _ = writeln!(out, "{} = {}", quote(key), quote(value));
        }
    }

    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn source_string(source: PackageSource) -> Option<&'static str> {
    match source {
        PackageSource::Path => None,
        PackageSource::Registry => Some(CRATES_IO_SOURCE),
    }
}

/// A TOML basic string.
fn quote(text: &str) -> String {
    let mut quoted = String::with_capacity(text.len() + 2);
    quoted.push('"');
    for character in text.chars() {
        match character {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\t' => quoted.push_str("\\t"),
            '\r' => quoted.push_str("\\r"),
            control if control.is_control() => {
                let _ = write!(quoted, "\\u{:04X}", u32::from(control));
            }
            other => quoted.push(other),
        }
    }
    quoted.push('"');
    quoted
}
