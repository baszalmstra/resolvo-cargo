//! Resolving with a previous `Cargo.lock`, as `cargo update` without
//! arguments does: the versions it pins are kept while they still fit and
//! stay usable after being yanked. Also the lock file encoding itself, and
//! under `resolver = "3"` the preference for versions whose
//! `rust-version` the workspace supports.

mod common;

use common::{case, dep_req, names, pkg, resolve};
use resolvo_cargo::ResolveError;

/// `root` depending on `x 0.2` and on `y`, which depends on `x 0.1`: two
/// versions of `x` in one lock file. `newer` adds `x 0.1.1` and `x 0.2.1`.
fn two_versions_of_x(newer: bool) -> common::Case {
    let mut registry = vec![
        pkg(("x", "0.1.0")),
        pkg(("x", "0.2.0")),
        pkg("y").deps([dep_req("x", "0.1")]),
    ];
    if newer {
        registry.extend([pkg(("x", "0.1.1")), pkg(("x", "0.2.1"))]);
    }
    case(registry, [dep_req("x", "0.2"), dep_req("y", "1")])
}

#[test]
fn a_locked_version_is_kept_although_a_newer_one_fits() -> anyhow::Result<()> {
    let lockfile = resolve(vec![pkg(("x", "1.0.0"))], [dep_req("x", "1")])??.to_string();
    let registry = vec![pkg(("x", "1.0.0")), pkg(("x", "1.0.1"))];
    let updated = case(registry, [dep_req("x", "1")])
        .previous(&lockfile)
        .resolve()??;
    insta::assert_snapshot!(names(&updated), @"
    root 1.0.0
    x 1.0.0
    ");
    Ok(())
}

#[test]
fn a_locked_version_stays_usable_after_being_yanked() -> anyhow::Result<()> {
    let lockfile = resolve(vec![pkg(("x", "1.0.0"))], [dep_req("x", "1")])??.to_string();
    let yanked = || vec![pkg(("x", "1.0.0")).yanked()];

    let locked = case(yanked(), [dep_req("x", "1")])
        .previous(&lockfile)
        .resolve()??;
    insta::assert_snapshot!(names(&locked), @"
    root 1.0.0
    x 1.0.0
    ");

    let fresh = resolve(yanked(), [dep_req("x", "1")])?;
    assert!(
        matches!(&fresh, Err(ResolveError::OnlyYanked { package, .. }) if package.as_str() == "x"),
        "{fresh:?}"
    );
    Ok(())
}

#[test]
fn resolver_3_prefers_versions_supporting_the_rust_version() -> anyhow::Result<()> {
    let resolve_with = |resolver: &str| -> anyhow::Result<String> {
        let registry = vec![
            pkg(("x", "1.0.0")).rust_version("1.60"),
            pkg(("x", "1.1.0")).rust_version("1.80"),
        ];
        let resolved = case(registry, [dep_req("x", "1")])
            .package_field("rust-version = \"1.70\"")
            .manifest_tail(&format!("\n[workspace]\nresolver = \"{resolver}\"\n"))
            .resolve()??;
        Ok(names(&resolved))
    };
    let resolved = format!(
        "resolver 3:\n{}resolver 2:\n{}",
        resolve_with("3")?,
        resolve_with("2")?
    );
    insta::assert_snapshot!(resolved, @"
    resolver 3:
    root 1.0.0
    x 1.0.0
    resolver 2:
    root 1.0.0
    x 1.1.0
    ");
    Ok(())
}

#[test]
fn two_versions_of_a_crate_are_told_apart_by_version() -> anyhow::Result<()> {
    let lockfile = two_versions_of_x(false).resolve()??.to_string();
    insta::assert_snapshot!(lockfile, @r#"
    # This file is automatically @generated by Cargo.
    # It is not intended for manual editing.
    version = 4

    [[package]]
    name = "root"
    version = "1.0.0"
    dependencies = [
     "x 0.2.0",
     "y",
    ]

    [[package]]
    name = "x"
    version = "0.1.0"
    source = "registry+https://github.com/rust-lang/crates.io-index"
    checksum = "7820302e312e3000000000000000000000000000000000000000000000000000"

    [[package]]
    name = "x"
    version = "0.2.0"
    source = "registry+https://github.com/rust-lang/crates.io-index"
    checksum = "7820302e322e3000000000000000000000000000000000000000000000000000"

    [[package]]
    name = "y"
    version = "1.0.0"
    source = "registry+https://github.com/rust-lang/crates.io-index"
    checksum = "7920312e302e3000000000000000000000000000000000000000000000000000"
    dependencies = [
     "x 0.1.0",
    ]
    "#);
    Ok(())
}

/// Resolving against a registry that gained newer versions, with the
/// written lock file as the previous one, writes it again byte for byte.
#[test]
fn resolving_with_the_written_lock_file_reproduces_it() -> anyhow::Result<()> {
    let lockfile = two_versions_of_x(false).resolve()??.to_string();
    let again = two_versions_of_x(true)
        .previous(&lockfile)
        .resolve()??
        .to_string();
    assert_eq!(again, lockfile);
    Ok(())
}
